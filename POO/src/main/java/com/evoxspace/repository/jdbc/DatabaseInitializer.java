package com.evoxspace.repository.jdbc;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public final class DatabaseInitializer {
    private DatabaseInitializer() {
    }

    public static void initialize(Connection connection) throws IOException, SQLException {
        try (InputStream input = DatabaseInitializer.class.getResourceAsStream("/db/schema.sql")) {
            if (input == null) throw new IOException("No se encontró /db/schema.sql");
            String schema = new String(input.readAllBytes(), StandardCharsets.UTF_8);
            try (Statement statement = connection.createStatement()) {
                for (String command : schema.split(";")) {
                    if (!command.isBlank()) statement.execute(command);
                }
                migrateVinColumn(statement);
                statement.execute("ALTER TABLE ordenes_reparacion ADD COLUMN IF NOT EXISTS "
                        + "numero_caso BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE");
                statement.execute("UPDATE ordenes_reparacion SET numero_caso = "
                        + "(SELECT COUNT(*) FROM ordenes_reparacion older "
                        + "WHERE older.fecha_ingreso < ordenes_reparacion.fecha_ingreso "
                        + "OR (older.fecha_ingreso = ordenes_reparacion.fecha_ingreso "
                        + "AND older.id <= ordenes_reparacion.id)) "
                        + "WHERE numero_caso IS NULL");
                try (var result = statement.executeQuery(
                        "SELECT COALESCE(MAX(numero_caso), 0) + 1 FROM ordenes_reparacion")) {
                    result.next();
                    statement.execute("ALTER TABLE ordenes_reparacion ALTER COLUMN numero_caso "
                            + "RESTART WITH " + result.getLong(1));
                }
            }
        }
    }

    private static void migrateVinColumn(Statement statement) throws SQLException {
        String type = null;
        try (var result = statement.executeQuery(
                "SELECT DATA_TYPE, CHARACTER_MAXIMUM_LENGTH FROM INFORMATION_SCHEMA.COLUMNS "
                        + "WHERE TABLE_NAME = 'VEHICULOS' AND COLUMN_NAME = 'VIN'")) {
            if (result.next()) {
                type = result.getString(1);
                if (type.toUpperCase().contains("CHARACTER VARYING") && result.getLong(2) <= 7) return;
            }
        }
        if (type == null) return;
        statement.execute("ALTER TABLE vehiculos ALTER COLUMN vin RENAME TO vin_legado");
        statement.execute("ALTER TABLE vehiculos ADD vin VARCHAR(7)");
        statement.execute("UPDATE vehiculos SET vin = TRIM(SUBSTRING(vin_legado, 1, 7))");
        statement.execute("ALTER TABLE vehiculos DROP COLUMN vin_legado");
        statement.execute("ALTER TABLE vehiculos ADD CONSTRAINT uq_vehiculos_vin UNIQUE (vin)");
    }
}
