CREATE TABLE IF NOT EXISTS clientes (
    id VARCHAR(36) PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehiculos (
    id VARCHAR(36) PRIMARY KEY,
    cliente_id VARCHAR(36) NOT NULL,
    vin VARCHAR(7) NOT NULL UNIQUE,
    marca VARCHAR(80) NOT NULL,
    modelo VARCHAR(80) NOT NULL,
    anio INTEGER NOT NULL,
    CONSTRAINT fk_vehiculo_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);

CREATE TABLE IF NOT EXISTS mecanicos (
    id VARCHAR(36) PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    especialidad VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS ordenes_reparacion (
    id VARCHAR(36) PRIMARY KEY,
    numero_caso BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    vehiculo_id VARCHAR(36) NOT NULL,
    mecanico_id VARCHAR(36),
    estado VARCHAR(30) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_entrega_estimada DATE,
    CONSTRAINT fk_orden_vehiculo FOREIGN KEY (vehiculo_id) REFERENCES vehiculos(id),
    CONSTRAINT fk_orden_mecanico FOREIGN KEY (mecanico_id) REFERENCES mecanicos(id)
);

CREATE TABLE IF NOT EXISTS diagnosticos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id VARCHAR(36) NOT NULL UNIQUE,
    codigo_dtc VARCHAR(30) NOT NULL,
    tipo_falla VARCHAR(40) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_diagnostico_orden FOREIGN KEY (orden_id) REFERENCES ordenes_reparacion(id)
);

CREATE TABLE IF NOT EXISTS cotizaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id VARCHAR(36) NOT NULL UNIQUE,
    mano_de_obra DECIMAL(12,2) NOT NULL,
    piezas DECIMAL(12,2) NOT NULL,
    aprobada BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_cotizacion_orden FOREIGN KEY (orden_id) REFERENCES ordenes_reparacion(id)
);

CREATE TABLE IF NOT EXISTS cotizacion_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    descripcion VARCHAR(300) NOT NULL,
    costo DECIMAL(12,2) NOT NULL,
    fecha_llegada_estimada DATE,
    CONSTRAINT fk_detalle_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id)
);

CREATE TABLE IF NOT EXISTS cotizacion_documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id BIGINT NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    ruta VARCHAR(500) NOT NULL,
    subido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_documento_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id)
);

CREATE TABLE IF NOT EXISTS piezas_refaccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id VARCHAR(36) NOT NULL,
    nombre VARCHAR(180) NOT NULL,
    fecha_estimada_llegada DATE NOT NULL,
    CONSTRAINT fk_pieza_orden FOREIGN KEY (orden_id) REFERENCES ordenes_reparacion(id)
);

CREATE TABLE IF NOT EXISTS documentos_evidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id VARCHAR(36) NOT NULL,
    nombre VARCHAR(180) NOT NULL,
    ruta VARCHAR(500) NOT NULL,
    CONSTRAINT fk_documento_orden FOREIGN KEY (orden_id) REFERENCES ordenes_reparacion(id)
);

CREATE TABLE IF NOT EXISTS mensajes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remitente_rol VARCHAR(20) NOT NULL,
    remitente_email VARCHAR(180) NOT NULL,
    destinatario_rol VARCHAR(20) NOT NULL,
    destinatario_email VARCHAR(180) NOT NULL,
    contenido VARCHAR(2000) NOT NULL,
    enviado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS solicitudes_cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_email VARCHAR(180) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    modelo_auto VARCHAR(120) NOT NULL,
    falla VARCHAR(1000) NOT NULL,
    contexto VARCHAR(2000) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
